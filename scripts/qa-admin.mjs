/*
 * A real upload, through the real control.
 *
 * This is the only assertion that exercises the `media admin write` Storage
 * policy — every other part of Content Studio would pass with that policy
 * broken, because nothing else writes to Storage. It picks a genuine file off
 * disk through `DOM.setFileInputFiles`, so the resize, the WebP conversion, the
 * browser client's session and the bucket policy all run exactly as they will
 * for the owner.
 *
 * The object is deleted afterwards. Nothing is saved, so the database is never
 * touched by it.
 */
let uploadedObject = null;
{
  await send('DOM.enable', {}, sessionId);

  const { result: handle } = await send(
    'Runtime.evaluate',
    { expression: 'document.querySelector(\'.cs-upload input[type="file"]\')', returnByValue: false },
    sessionId
  );

  if (!handle?.objectId) {
    ok('a photo can be uploaded', false, 'no file input on the fleet screen');
  } else {
    await send('DOM.setFileInputFiles', { files: [SAMPLE_IMAGE], objectId: handle.objectId }, sessionId);

    const landed = await waitFor(
      `!!document.querySelector('.cs-upload-row input.ar-field__input')?.value?.startsWith('fleet/')`,
      20000
    );

    const pathValue = await evalIn(
      'document.querySelector(".cs-upload-row input.ar-field__input")?.value ?? ""'
    );
    const problem = await evalIn(
      'document.querySelector(\'.cs-upload [role="alert"]\')?.textContent ?? ""'
    );

    ok('a photo uploads and returns a Storage path', landed, problem || `path is "${pathValue}"`);

    if (landed) {
      uploadedObject = pathValue;
      const shrunk = await evalIn(`(() => {
        const hints = [...document.querySelectorAll('.cs-upload .cs-hint')].map(h => h.textContent);
        return hints.find(h => /KB setelah dikecilkan/.test(h)) ?? '';
      })()`);
      ok('…and reports the size it was reduced to', /KB/.test(shrunk), shrunk || 'no size reported');
    }
  }
}

